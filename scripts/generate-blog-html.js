/**
 * Blog Build Script
 *
 * Reads markdown files from /public/blog/ with YAML frontmatter and:
 * 1. Generates blogPosts.js (metadata)
 * 2. Generates blogContent.js (content)
 * 3. Generates SEO-friendly HTML files for each blog page
 *
 * To add a new blog post:
 * 1. Create a .md file in /public/blog/ with frontmatter (see existing posts)
 * 2. Run npm run build
 *
 * Frontmatter format:
 * ---
 * title: "Your Post Title"
 * slug: "your-post-slug"
 * excerpt: "Short description for SEO"
 * category: "Category Name"
 * date: "YYYY-MM-DD"
 * readTime: 10
 * author: "Author Name"
 * tags: ["Tag1", "Tag2"]
 * relatedSlugs: ["other-post-slug"]
 * ---
 */

const fs = require('fs');
