const srcDataDir = path.join(__dirname, '..', 'src', 'data');
const buildDir = path.join(__dirname, '..', 'build');

// Simple YAML frontmatter parser
function parseFrontmatter(content) {
  // Normalize Windows line endings to Unix and strip BOM
  content = content.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const frontmatterRegex = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/;
  const match = content.match(frontmatterRegex);

  if (!match) {
    return { metadata: {}, content };
  }

  const yamlStr = match[1];
  const markdownContent = match[2];

  // Parse YAML manually (simple key-value pairs)
  const metadata = {};
  const lines = yamlStr.split('\n');

  for (const line of lines) {
    const colonIndex = line.indexOf(':');
    if (colonIndex === -1) continue;

    const key = line.substring(0, colonIndex).trim();
    let value = line.substring(colonIndex + 1).trim();

    // Handle quoted strings
    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    // Handle arrays
    else if (value.startsWith('[')) {
      try {
        value = JSON.parse(value);
      } catch (e) {
        // Keep as string if parsing fails
      }
    }
    // Handle numbers
    else if (!isNaN(value) && value !== '') {
      value = Number(value);
    }

    metadata[key] = value;
  }

  return { metadata, content: markdownContent.trim() };
}

// Read all blog posts from /public/blog/
function readBlogPosts() {
  const files = fs.readdirSync(publicBlogDir).filter(f => f.endsWith('.md'));
  const posts = [];

  for (const file of files) {
    const filePath = path.join(publicBlogDir, file);
    const fileContent = fs.readFileSync(filePath, 'utf8');
    const { metadata, content } = parseFrontmatter(fileContent);

    if (!metadata.slug) {
      console.warn(`Warning: ${file} is missing slug in frontmatter, skipping`);
      continue;
    }

    posts.push({
      ...metadata,
      content
    });
  }

  // Sort by date (newest first)
  posts.sort((a, b) => new Date(b.date) - new Date(a.date));

  return posts;
}

// Generate blogPosts.js
function generateBlogPostsJs(posts) {
  const postsWithoutContent = posts.map(({ content, ...rest }) => rest);

  const jsContent = `// Blog posts metadata
// Auto-generated by scripts/generate-blog-html.js
// Do not edit directly - edit the .md files in /public/blog/ instead

export const blogPosts = ${JSON.stringify(postsWithoutContent, null, 2)};
`;

  fs.writeFileSync(path.join(srcDataDir, 'blogPosts.js'), jsContent);
  console.log('Generated: src/data/blogPosts.js');
}

// Generate blogContent.js
function generateBlogContentJs(posts) {
  const jsContent = `// Blog content (markdown)
// Auto-generated by scripts/generate-blog-html.js
// Do not edit directly - edit the .md files in /public/blog/ instead

export const blogContent = {
${posts.map(post => `  '${post.slug}': ${JSON.stringify(post.content)}`).join(',\n')}
};
`;

  fs.writeFileSync(path.join(srcDataDir, 'blogContent.js'), jsContent);
  console.log('Generated: src/data/blogContent.js');
}

// Generate SEO HTML files
function generateSeoHtml(posts) {
  // Read the main index.html to extract JS/CSS paths
  const indexHtmlPath = path.join(buildDir, 'index.html');

  if (!fs.existsSync(indexHtmlPath)) {
    console.log('Build directory not found, skipping HTML generation');
    return;
  }

  const indexHtml = fs.readFileSync(indexHtmlPath, 'utf8');

  // Extract JS and CSS file paths from the built index.html
  const jsMatch = indexHtml.match(/src="(\/static\/js\/main\.[^"]+\.js)"/);
  const cssMatch = indexHtml.match(/href="(\/static\/css\/main\.[^"]+\.css)"/);
  const jsPath = jsMatch ? jsMatch[1] : '/static/js/main.js';
  const cssPath = cssMatch ? cssMatch[1] : '/static/css/main.css';

  console.log(`Found JS: ${jsPath}`);
  console.log(`Found CSS: ${cssPath}`);

  // Generate blog list page
  generateBlogListHtml(posts, jsPath, cssPath);

  // Generate individual blog post pages
  for (const post of posts) {
    generateBlogPostHtml(post, jsPath, cssPath);
  }
}

